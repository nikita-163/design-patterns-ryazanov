"""
Задача 11. Часы, минуты, секунды

Прочитайте целое число секунд (не меньше 0) и выведите, сколько в нём полных
часов, минут и секунд — три строки:

    Часов: <полные часы>
    Минут: <полные минуты сверх часов>
    Секунд: <остаток секунд>

Пример
------
Ввод:
10000
Вывод:
Часов: 2
Минут: 46
Секунд: 40

Подсказка
---------
Удобно применить divmod дважды: сначала к общему числу секунд и 3600,
затем к остатку и 60.
"""
# TODO: прочитайте число секунд
total_seconds = int(input())

# TODO: выведите часы, минуты и секунды с подписями
hours, rest = divmod(total_seconds, 3600)
minutes, seconds = divmod(rest, 60)

print(f'Часов: {hours}')
print(f'Минут: {minutes}')
print(f'Секунд: {seconds}')
