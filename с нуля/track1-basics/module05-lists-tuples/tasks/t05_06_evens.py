"""
Задача 05-06. Только чётные

Прочитайте числа через пробел и выведите только чётные из них — одной
строкой через пробел, в исходном порядке. Если чётных нет — ничего
не выводите.

Пример
------
Ввод:
1 2 3 4 5 6
Вывод:
2 4 6
"""

# TODO: соберите чётные числа в новый список и выведите его
parts = input().split()
numbers = []
for p in parts:
    numbers.append(int(p))

evens = []
for x in numbers:
    if x % 2 == 0:
        evens.append(str(x))

if evens:
    print(' '.join(evens))

