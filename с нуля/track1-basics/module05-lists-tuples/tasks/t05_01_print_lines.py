"""
Задача 05-01. Построчно

Прочитайте строку с числами, разделёнными пробелами, и выведите каждое
число с отдельной строки (в том же порядке).

Пример
------
Ввод:
3 7 1
Вывод:
3
7
1
"""

# TODO: разберите строку и выведите элементы построчно
parts = input().split()
numbers = []
for p in parts:
    numbers.append(int(p))

for x in numbers:
    print(x)

