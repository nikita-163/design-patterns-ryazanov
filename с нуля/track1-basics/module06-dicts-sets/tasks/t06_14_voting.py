"""
Задача 06-14. Голосование

Прочитайте целое число n, затем n строк — имена проголосовавших (по одному
имени в строке). Выведите победителя и число голосов: «имя количество».

Победитель — набравший больше всех голосов; если сразу несколько набрали
максимум, побеждает имя, идущее раньше по алфавиту.

Пример
------
Ввод:
5
борис
анна
борис
анна
анна
Вывод:
анна 3
"""

# TODO: подсчёт голосов словарём и выбор победителя с учётом ничьих
n = int(input())

votes = {}
for _ in range(n):
    name = input()
    if name not in votes:
        votes[name] = 0
    votes[name] += 1

winner = ''
best_count = 0
for name in sorted(votes):
    if votes[name] > best_count:
        winner = name
        best_count = votes[name]

print(f'{winner} {best_count}')

