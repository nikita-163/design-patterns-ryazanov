"""
Задача 02-17 ★. Билет в кино

Билет стоит 300 рублей. Прочитайте два целых числа:

1. возраст зрителя;
2. час начала сеанса (от 0 до 23).

Скидки применяются последовательно, одна поверх другой:

- если возраст меньше 12 лет — цена уменьшается вдвое;
- если сеанс начинается до 18:00 — к текущей цене применяется скидка 20%.

Выведите итоговую цену, округлённую до 2 знаков.

Пример
------
Ввод:
10
15
Вывод:
120.0
"""

# TODO: прочитайте возраст и час, примените скидки и выведите итог
age = int(input())
hour = int(input())

price = 300.0

if age < 12:
    price = price / 2

if hour < 18:
    price = price * 80 / 100

print(round(price, 2))

