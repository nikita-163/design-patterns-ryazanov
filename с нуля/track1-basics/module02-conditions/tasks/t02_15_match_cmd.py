"""
Задача 02-15. Команды (match)

Прочитайте команду (строку) и обработайте её оператором match:

- «старт» → вывести «запуск»;
- «стоп» → вывести «остановка»;
- любая другая → вывести «неизвестная команда».

Пример
------
Ввод:
старт
Вывод:
запуск
"""

# TODO: прочитайте команду и обработайте её через match/case
command = input()

match command:
    case 'старт':
        print('запуск')
    case 'стоп':
        print('остановка')
    case _:
        print('неизвестная команда')

