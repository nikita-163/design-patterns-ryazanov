"""
Задача 02-10. Корни квадратного уравнения

Прочитайте коэффициенты a, b, c квадратного уравнения ax² + bx + c = 0
(целые числа, a ≠ 0). Вычислите дискриминант D = b² − 4ac и выведите:

- «нет корней» — если D < 0;
- «один корень: X» — если D = 0 (X округлите до 3 знаков);
- «два корня: X Y» — если D > 0, корни по возрастанию, каждый округлите
  до 3 знаков.

Пример
------
Ввод:
1
-3
2
Вывод:
два корня: 1.0 2.0
"""

import math

# TODO: прочитайте коэффициенты, вычислите дискриминант и выведите корни
a = int(input())
b = int(input())
c = int(input())

d = b ** 2 - 4 * a * c

if d < 0:
    print('нет корней')
elif d == 0:
    x = -b / (2 * a)
    print(f'один корень: {round(x, 3)}')
else:
    root_d = math.sqrt(d)
    x1 = (-b - root_d) / (2 * a)
    x2 = (-b + root_d) / (2 * a)
    if x1 > x2:
        x1, x2 = x2, x1
    print(f'два корня: {round(x1, 3)} {round(x2, 3)}')

