"""
Задача 03-15. Лестница из звёздочек

Прочитайте целое число n (n ≥ 1) и выведите n строк: первая — одна
звёздочка, вторая — две, и так далее.

Пример
------
Ввод:
4
Вывод:
*
**
***
****
"""

# TODO: выведите n строк-«ступеней» из звёздочек
n = int(input())

for i in range(1, n + 1):
    for _ in range(i):
        print('*', end='')
    print()

