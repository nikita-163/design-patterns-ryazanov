"""
Задача 03-06. Сколько чисел кратны семи

Прочитайте целое число n (n ≥ 1). Посчитайте, сколько чисел от 1 до n
делятся на 7 без остатка, и выведите количество.

Пример
------
Ввод:
50
Вывод:
7
"""

# TODO: посчитайте циклом количество чисел, кратных 7
n = int(input())

count = 0
for i in range(1, n + 1):
    if i % 7 == 0:
        count += 1

print(count)

