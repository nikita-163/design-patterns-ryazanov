"""
Задача 03-03. Сумма цифр числа

Прочитайте целое число n (n ≥ 0) и выведите сумму его цифр.

Разбирайте число в цикле операциями % 10 и // 10 — без преобразования
в строку.

Пример
------
Ввод:
12345
Вывод:
15
"""

# TODO: прочитайте n и посчитайте сумму цифр циклом
n = int(input())

total = 0
while n > 0:
    total += n % 10
    n //= 10

print(total)

